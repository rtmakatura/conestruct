"""#316 (R129 Q6) probe: the near-intersection plan sheet's NOTES box as
rendered, with neither, the cross-street line only, and both guessed-speed
lines.  Renders page 1 through the API (TestClient, Overpass stubbed) and
saves the bottom band of the page (where the NOTES & SIGN SCHEDULE box sits)
as PNGs, plus the page text, so the box can be checked by eye and by text.

Usage: python notes_render_probe.py <repo-root> <out-dir>
"""

from __future__ import annotations

import copy
import os
import sys
from pathlib import Path
from typing import Any

ROOT = Path(sys.argv[1]).resolve()
OUT = Path(sys.argv[2])
OUT.mkdir(parents=True, exist_ok=True)
sys.path.insert(0, str(ROOT))
os.environ["RENDER_API_SECRET"] = "probe"
AUTH = {"Authorization": "Bearer probe"}

import pypdfium2 as pdfium  # noqa: E402
from fastapi.testclient import TestClient  # noqa: E402

from src.api.render_api import app  # noqa: E402
from src.rules import site_detection as sd  # noqa: E402
from src.rules.corridor import _destination_point  # noqa: E402

sd._overpass_request_with_fallback = lambda *_a, **_kw: ({"elements": []}, None)  # type: ignore[assignment]

PIN = (39.7400, -104.9600)
cross = _destination_point(*PIN, 0.0, 700.0 * 0.3048)
base: dict[str, Any] = {
    "kind": "near_intersection",
    "meta": {
        "project": "notes probe", "address": "", "lat": PIN[0], "lng": PIN[1],
        "pinModel": "work_start", "work": {"side": "right", "heading": "N"},
        "intersection": {"lat": cross[0], "lng": cross[1], "name": "E 17th Ave"},
    },
    "roadType": "urban_arterial", "speed": 25, "lanes": 2, "laneWidth": 12,
    "divided": False, "workType": "utility_cut", "duration": "short",
    "workLen": 500, "night": False,
    "approaches": [
        {"id": "cross_a", "speed": 25, "roadType": "urban_arterial",
         "lanesPerDirection": 1, "laneWidth": 12, "signalized": False},
        {"id": "cross_b", "speed": 25, "roadType": "urban_arterial",
         "lanesPerDirection": 1, "laneWidth": 12, "signalized": False},
    ],
}
cases = {
    "neither": {},
    "cross-street": {"approach_speed": {"highwayClass": "residential"}},
    "both": {"speed": {"highwayClass": "residential"},
             "approach_speed": {"highwayClass": "residential"}},
}
client = TestClient(app)
for label, g in cases.items():
    body = copy.deepcopy(base)
    if g:
        body["guesses"] = g
    r = client.post("/render/pdf", headers=AUTH, json=body)
    assert r.status_code == 200, r.text[:300]
    pdf = pdfium.PdfDocument(r.content)
    page = pdf[0]
    w, h = page.get_size()
    text = page.get_textpage().get_text_range()
    img = page.render(scale=3).to_pil()
    # The footer boxes span the page's bottom band.
    img.crop((0, int(img.height * 0.70), img.width, img.height)).save(OUT / f"notes-{label}.png")
    flat = " ".join(text.split())
    print(f"== {label}: page {w:.0f}x{h:.0f} pt")
    for needle in (
        "SPEED GUESSED FROM THE ROAD CLASS",
        "CROSS-STREET SPEED GUESSED FROM THE ROAD CLASS",
        "APPLY AS DRAWN.",
        "GENERATED BY CONESTRUCT",
        "Verify all dimensions before use.",
    ):
        print(f"   {needle!r}: {flat.count(needle)}")
